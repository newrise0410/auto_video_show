"""LLM 스테이지가 쓰는 프롬프트와, 백엔드가 읽는 작업 헤더.

시스템 프롬프트 앞에 `AVS-TASK` / `AVS-META` 두 줄을 붙인다. 실제 모델은 이걸
그냥 맥락으로 받고, mock 백엔드는 여기서 무엇을 흉내 낼지 읽는다.
"""

from __future__ import annotations

import json

from .models import Profile

TASK_LINE = "AVS-TASK:"
META_LINE = "AVS-META:"

#: 내레이션 평균 길이의 하한 = 상한의 이 비율.
#: 상한만 주면 모델이 안전하게 굴어 예산의 절반만 쓰고, 영상이 통째로 짧아진다.
#: 씬별이 아니라 평균에 거는 이유는 짧고 강한 한 줄도 정당한 연출이기 때문이다.
NARRATION_FLOOR_RATIO = 0.75


def narration_floor(limit: int) -> int:
    """내레이션 평균 글자수의 하한."""
    return int(limit * NARRATION_FLOOR_RATIO)


#: s1·s2가 공유하는 한국어 낱말 기준.
#:
#: 관측된 실패는 번역투가 아니었다 — 피동 1건, '~에 대한' 0건, '~것입니다' 0건.
#: 진짜 문제는 추상 한자어가 엉뚱한 분야의 말투를 끌고 오는 것이었다. 저주가
#: '성립'하고(계약), 대가가 '청구'되고(회계), 약속을 '무력화'한다(군사).
#: 글로 읽으면 지나가지만 소리로 들으면 장면이 안 그려진다.
#:
#: 이 기준이 s1에도 닿아야 한다. 관측된 여섯 개가 전부 구성안에서 태어났다.
#: `Profile.style_notes` 에 넣지 않는 이유는 이 규칙이 포맷과 무관한데
#: style_notes 는 프로파일별이라 YAML 세 곳에 복제되기 때문이다.
KOREAN_DICTION = """\
낱말 기준 — 글이 아니라 소리:
- 추상 한자어로 요약하지 말고 눈에 보이는 일로 쓰세요. 다른 분야에서 빌려온
  말은 장면을 지웁니다.
    "저주가 성립했다"(계약)           → "저주가 걸렸다"
    "대가는 청구되지 않았다"(회계)      → "대가는 아직 날아오지 않았다"
    "약속을 시간으로 무력화했다"(군사)   → "약속이 영영 오지 않게 만들었다"
    "정면 승부는 선택지가 아니었다"(게임) → "정면으로 붙으면 죽는다"
    "모욕을 견디는 게 그의 전술이었다"(군사) → "그래서 맞고도 참았다"
    "첫 기항지"(해운)                 → "처음 배를 댄 섬"
- 한자어를 무조건 피하라는 뜻이 **아닙니다**. 기준은 하나입니다 —
  **소리 내어 읽었을 때 한 번에 알아들리는가.**\
"""


def task_header(task: str, meta: dict[str, object] | None = None) -> str:
    payload = json.dumps(meta or {}, ensure_ascii=False)
    return f"{TASK_LINE} {task}\n{META_LINE} {payload}"


def parse_task_header(system: str) -> tuple[str, dict[str, str]]:
    task = ""
    meta: dict[str, str] = {}
    for line in system.splitlines()[:4]:
        line = line.strip()
        if line.startswith(TASK_LINE):
            task = line[len(TASK_LINE) :].strip()
        elif line.startswith(META_LINE):
            try:
                raw = json.loads(line[len(META_LINE) :].strip())
            except json.JSONDecodeError:
                raw = {}
            meta = {str(k): str(v) for k, v in raw.items()}
    return task, meta


# --------------------------------------------------------------------- s1 기획


def outline_system(profile: Profile, topic: str) -> str:
    return task_header(
        "outline", {"topic": topic, "profile": profile.name, "beats": profile.max_scenes}
    ) + f"""

당신은 한국어 영상 기획자입니다. 주제 하나를 받아 {profile.name} 포맷
({profile.aspect_label}, 약 {int(profile.target_duration)}초) 영상의 구성안을 씁니다.

**이 구성안이 영상의 *내용*을 확정합니다.** 대본 작가는 무엇을 다룰지 다시
고르지 않습니다. 그러니 백과사전식 요약을 옮기지 말고, 무엇을 버릴지 여기서
결정하세요.

**문장은 대본 작가가 다시 씁니다.** 여기 적은 표현이 그대로 낭독되지는
않습니다. 사실을 정확히 적는 데 집중하세요. 다만 여기서 뭉뚱그린 말은 거기서도
뭉뚱그려집니다 — 대본 작가는 여기 없는 사실을 만들어내지 못하니까요.

출력은 마크다운 한 편입니다. 다른 설명이나 인사말을 붙이지 마세요.
다음 항목을 포함하세요:

- `# 제목` — 클릭을 부르되 과장하지 않는 제목
- `## 논지` — 이 영상이 증명할 문장 **하나**. 아래 모든 항목이 여기에 복무합니다.
- `## 훅` — 첫 3초에 쓸 문장 후보 2개
- `## 전개` — {profile.max_scenes}개 안팎. 각 항목은 한 줄이고 **태그 두 개**로
  시작합니다. 형식: `- [핵심][그래서] 내용` / `- [선택][하지만] 내용`
  · 첫 태그 — `[핵심]` 은 빼면 논지가 무너지는 항목, `[선택]` 은 있으면 좋은
    항목. 논지의 근거가 되는 항목이 최소 하나는 `[핵심]` 이어야 합니다.
  · 둘째 태그 — **이 항목이 바로 앞 항목과 맺는 관계**입니다. 셋 중 하나입니다.
      `[그래서]` 앞 항목 때문에 이 일이 벌어졌다 (인과)
      `[하지만]` 앞 항목이 만든 기대가 여기서 뒤집힌다 (반전)
      `[전환]`   새 챕터를 여는 항목. 전체에서 3~4개, 맨 앞 항목은 항상 이것
  · **`[그리고]` 라는 태그는 없습니다.** 앞 항목과 '그래서' 로도 '하지만' 으로도
    이어지지 않는 항목은 그냥 나열입니다. 지우거나, 앞 항목과 합치거나,
    순서를 바꿔서 인과가 생기게 하세요. 줄거리를 시간순으로 훑으면 전부
    나열이 됩니다.
  · `[하지만]` 이 전체의 4분의 1 미만이면 갈등 없이 설명만 하고 있는 겁니다.
  흔한 요약에 늘 들어가는 항목이라도 논지에 복무하지 않으면 빼고, 그 자리에
  논지를 **증명하는** 장면을 넣으세요.
- `## 마무리` — 마지막에 남길 메시지. 논지를 근거 없이 선언하지 말고,
  `## 전개` 에서 실제로 보여준 장면 위에서 닫으세요.
- `## 참고` — 사실 확인이 필요한 지점이 있으면 명시

{KOREAN_DICTION}

{profile.style_notes}"""


def outline_user(topic: str) -> str:
    return f"주제: {topic}\n\n이 주제로 구성안을 작성하세요."


# --------------------------------------------------------------------- s2 대본


def script_system(profile: Profile, topic: str, scene_count: int) -> str:
    limit = profile.narration_limit
    floor = narration_floor(limit)
    return task_header(
        "script",
        {
            "topic": topic,
            "profile": profile.name,
            "scenes": scene_count,
            "max_chars": limit,
            "min_avg_chars": floor,
        },
    ) + f"""

당신은 한국어 영상 대본 작가입니다. 구성안을 받아 씬 단위 대본을 JSON으로 씁니다.

절대 규칙:
1. 출력은 JSON 객체 **하나뿐**입니다. 코드펜스, 주석, 설명을 붙이지 마세요.
2. 씬은 정확히 {scene_count}개입니다. `index`는 1부터 {scene_count}까지 연속입니다.
3. 각 씬의 `narration`은 공백 포함 {limit}자 이하입니다. 초과하면 반려됩니다.
   **이 상한은 목표치이지 절약할 예산이 아닙니다.** 씬 길이는 고정이 아니라
   합성된 목소리의 실측 길이가 정하므로, 짧게 쓰면 영상이 그만큼 짧아지고
   구성안의 내용이 통째로 사라집니다. 평균 {floor}자 이상을 쓰세요.
   짧게 끊는 건 리듬을 위해 의도적으로 고른 한두 씬에서만 하세요.
4. 각 씬의 `narration`은 **소리 내어 읽을 한국어**입니다. 글로 훑는 요약문이
   아니라 나레이터가 실제로 발음할 문장입니다. 아래를 지키세요.
   - 명사로 끝나는 헤드라인체를 쓰지 않습니다
     ("목마 계략의 주인공, 목표는 오직 고향" ✗).
   - 연결어미를 줄여 쓰지 않습니다. "라 답합니다" ✗ → "라고 답합니다" ✓,
     "며 돌아갑니다" ✗ → "면서 돌아갑니다" ✓. "…했다고." 처럼 어미로
     끝나는 조각 문장도 쓰지 않습니다.
   - 조사를 줄이지 않습니다. "있진" ✗ → "있지는" ✓.
   - 관형절을 겹쳐 쌓지 않습니다. "부하들이 잡아먹히던 동굴에서 거인이
     이름을 묻자…" 처럼 수식이 길어지면 문장을 나누세요.
   - **한 씬에 문장 두세 개를 써도 됩니다.** 한 문장에 다 밀어 넣어
     압축하지 말고, 짧은 문장 여러 개로 자연스럽게 푸세요.
   - **문장 끝을 굴리세요.** `~습니다` 로만 끝내면 {scene_count}씬 내내 같은
     박자가 반복돼 귀가 닫힙니다. `~습니다` 가 **여섯 문장을 넘겨 연달아**
     나오지 않게 하고, 전체의 3분의 1쯤은 다른 방식으로 끝내세요.
     쓸 수 있는 것: `~죠` / `~더군요` / `~던 겁니다` / `~거든요` /
     되묻기("왜 그랬을까요?") / 인용을 그대로 두기("아무도 나를 해치지 않았다.")
     의문형은 대본 전체에서 두세 번까지만. 남발하면 싸구려 유튜브 톤이 됩니다.
   - **주어를 매번 부르지 마세요.** 한 씬에서 사람 이름이나 대명사는 처음 한 번만
     쓰고, 그다음 문장은 주어 없이 이어갑니다. 한국어는 주어를 생략하는 언어라
     "그는 …했습니다. 그는 …했습니다" 는 두 번째 '그는' 을 지우는 편이 자연스럽습니다.
5. **씬은 앞 씬을 받아서 엽니다.** 구성안 항목의 둘째 태그가 그 씬이 앞 씬과
   맺는 관계입니다. 그 관계를 첫 문장에 드러내세요.
     `[그래서]` → "그래서" "그러자" "결국" "그 대가로" "덕분에"
     `[하지만]` → "하지만" "그런데" "문제는" "대신" "오히려"
     `[전환]`   → 새 장을 여는 한마디로 엽니다
   최소 **네 씬에 한 씬**은 이렇게 앞을 받는 말로 열어야 합니다. 다만 매번
   "그래서"로 시작하면 그것대로 지겹습니다 — 같은 연결어를 연달아 두 번 쓰지 말고,
   접속부사 대신 앞 씬의 말을 되받는 방법도 씁니다("그 바위는…", "그 이름이…").
   구성안에 둘째 태그가 없으면(예전 구성안) 앞 항목과의 관계를 스스로 판단해 채우세요.
6. 구성안의 문장을 **어미만 바꿔 옮기지 마세요.** ("…했다" → "…했습니다" ✗)
   구성안은 무엇을 말할지 정한 목록이고, 당신이 하는 일은 그 내용을 **입으로
   말할 한국어로 다시 쓰는 것**입니다. 사실은 하나도 바꾸지 말고, 문장은 전부
   다시 쓰세요.
7. 구성안의 `[핵심]` 항목은 반드시 씬으로 만듭니다. 항목이 씬 수보다 많으면
   `[선택]` 중 논지에 덜 기여하는 것을 **버리세요**. 전부 담으려고 여러 항목을
   한 씬에 욱여넣지 마세요 — 이름만 나열한 씬("키르케와 세이렌, 카립디스를
   지나갑니다")은 아무것도 전달하지 못합니다. 남긴 항목은 고유명사를 살려
   구체적으로 쓰고, 버린 항목은 미련 없이 버립니다.
8. 1번 씬의 `narration`은 구성안 `## 훅` 의 후보 중 하나를 골라 씁니다.
   그대로 쓰거나 {limit}자에 맞게 다듬되, 훅을 버리고 새로 쓰지 마세요.
9. 구성안에 `## 참고` 가 있으면 **그 지시를 지킵니다.** 사실 확인 결과이므로
   대본과 `on_screen_text` 가 이를 어기면 안 됩니다.
10. `video_prompt`는 **영어**로 씁니다. 영상 생성 모델에 그대로 들어갑니다.
   피사체, 동작, 카메라 워크, 조명, 분위기를 담고 화면에 글자가 나오지 않게 합니다.
   실존 인물의 이름이나 상표를 쓰지 마세요.
11. `on_screen_text`는 화면에 띄울 짧은 한국어 키워드입니다. 12자 이하.

스키마:
{{
  "title": "문자열",
  "description": "문자열 (2~3문장)",
  "hashtags": ["#태그", ...],
  "scenes": [
    {{"index": 1, "narration": "…", "video_prompt": "…", "on_screen_text": "…"}}
  ]
}}

포맷: {profile.name} ({profile.aspect_label})
{KOREAN_DICTION}

{profile.style_notes}"""


def script_user(topic: str, outline: str, scene_count: int) -> str:
    return (
        f"주제: {topic}\n\n"
        f"구성안:\n{outline}\n\n"
        f"위 구성안의 내용을 {scene_count}개 씬 대본으로 **다시 쓰세요**. "
        f"무엇을 말할지는 구성안이 정했고, 어떻게 말할지는 당신이 정합니다. "
        f"JSON만 출력하세요."
    )


def script_retry_user(
    topic: str,
    outline: str,
    scene_count: int,
    previous: str | None,
    problems: list[str],
) -> str:
    """재시도 메시지.

    백엔드에 대화 기록이 없다 — `LLMBackend.complete()` 는 매번 새 프로세스다
    (`avs/backends/base.py`). 그래서 문제 목록만 보내면 모델은 구성안도 자기
    직전 출력도 못 본 채 처음부터 다시 쓰게 되고, "씬 14의 어미를 바꾸세요"
    같은 지적이 실행 불가능해진다. 첫 메시지를 통째로 다시 붙이고 직전 출력을
    함께 보낸다.

    지적하지 않은 씬을 그대로 두게 하는 건 문체 문제가 아니라 비용 문제다.
    내레이션이 그대로면 `text_sha` 가 같아 재합성을 건너뛰고, `video_prompt`
    가 그대로면 s3가 클립을 재사용한다.
    """
    joined = "\n".join(f"- {p}" for p in problems)
    parts = [script_user(topic, outline, scene_count)]
    if previous:
        parts.append("직전에 당신이 낸 출력입니다:\n" + previous)
    parts.append(
        "직전 출력에 아래 문제가 있습니다. 모두 고쳐서 JSON 객체 하나만 다시 "
        "출력하세요. **지적하지 않은 씬은 그대로 두세요** — 특히 `video_prompt` 는 "
        "손대지 마세요.\n\n" + joined
    )
    return "\n\n".join(parts)
